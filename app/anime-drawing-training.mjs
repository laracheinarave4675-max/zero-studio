export function getAnimeDrawingStudy(skillId) {
  const study = STUDIES[String(skillId ?? "")];
  if (!study) fail("No detailed anime drawing study exists for this skill.");
  return clone({ skillId, ...study });
}

/** Build a complete practice session with drawing order and honest evaluation boundaries. */
export function createAnimeDrawingSession({ skillId, characterId = "", referenceId = "", difficulty = "foundation" } = {}) {
  const catalog = ANIME_ARTIST_SKILL_CATALOG.find(item => item.id === skillId);
  if (!catalog) fail("Unknown anime drawing skill.");
  if (!["foundation", "intermediate", "advanced"].includes(difficulty)) fail("Unsupported anime drawing difficulty.");
  const study = getAnimeDrawingStudy(skillId);
  const scale = difficulty === "foundation" ? "أشكال كبيرة وخطوط بناء بسيطة" : difficulty === "intermediate" ? "تفاصيل متوسطة مع زوايا إضافية" : "تفاصيل دقيقة مع منظور وتعبير وحركة";
  return {
    format: "zero-studio-anime-drawing-session",
    version: 1,
    id: "anime-study-" + skillId + "-" + difficulty,
    skillId,
    title: study.title,
    characterId: String(characterId).slice(0, 120),
    referenceId: String(referenceId).slice(0, 120),
    difficulty,
    principle: study.principle,
    focus: [...study.focus],
    sequence: [...study.sequence],
    mistakesToAvoid: [...study.mistakes],
    rubric: study.rubric.map(([id, description]) => ({ id, description, evaluation: "human-review-unless-a-matching-raster-eye-is-implemented" })),
    deliverable: study.deliverable,
    drawingMedium: "native-canvas2d-raster-brush-strokes",
    recommendedScale: scale,
    drawingLayers: ["construction", "rough", "clean-ink", "flat-color", "cel-shadow", "highlight", "detail"],
    noImageGeneration: true,
    automaticMasteryAllowed: false,
    status: "ready-to-practice"
  };
}

/** Expose the list of detailed studies without leaking mutable internal arrays. */
export function listAnimeDrawingStudies() {
  return Object.keys(STUDIES).map(skillId => ({ skillId, title: STUDIES[skillId].title }));
}
